// Bundles socket.io-client (v2, the version Homey's realtime API speaks; MIT) into settings/socket.io.js for the
// web dashboards page (settings/dashboard.html), which uses it for our app's realtime events. Served by the Homey
// itself, so the page needs nothing from the internet. Run it after updating socket.io-client: `npm run web-socket`.
import { readFileSync } from 'node:fs';
import { build } from 'esbuild';

const { version } = JSON.parse(readFileSync('node_modules/socket.io-client/package.json', 'utf8'));

await build({
  stdin: { contents: "window.io = require('socket.io-client');", resolveDir: '.', loader: 'js' },
  bundle: true,
  format: 'iife',
  platform: 'browser',
  minify: true,
  legalComments: 'none',
  define: { global: 'window' },
  banner: { js: `/* Generated by scripts/build-web-socket.mjs (\`npm run web-socket\`); don't edit. socket.io-client ${version} (MIT). */` },
  outfile: 'settings/socket.io.js',
  logLevel: 'info',
});
