// Renders the Flow Buttons icon previews for the settings' autocomplete into lib/flowIconImages.ts: PNG data URLs,
// since the phone apps draw an item's `image` as a bitmap and showed nothing for an SVG (iOS, 2026-10-08).
// Run it after changing `ICONS` in widgets/flows/public/widget.js: `npm run flow-icons`.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import sharp from 'sharp';

const SIZE = 96; // 3x a 32 px row image

const win = {};
vm.runInNewContext(readFileSync('widgets/flows/public/widget.js', 'utf8'), { window: win });
const icons = win.FLOW_BUTTON_ICON_PATHS;

const lines = [];
for (const [id, icon] of Object.entries(icons)) {
  // The widget's button: the white glyph, 18 of 32 px, on Homey's blue.
  const paint = icon.fill ? 'fill="#fff"'
    : 'fill="none" stroke="#fff" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 32 32">`
    + '<circle cx="16" cy="16" r="16" fill="#2F8DF6"/>'
    + `<path transform="translate(7 7) scale(.75)" d="${icon.d}" ${paint}/></svg>`;
  const png = await sharp(Buffer.from(svg)).png({ compressionLevel: 9, palette: true }).toBuffer();
  lines.push(`  ${id}: { d: ${JSON.stringify(icon.d)}, image: 'data:image/png;base64,${png.toString('base64')}' },`);
}

writeFileSync('lib/flowIconImages.ts', `// Generated by scripts/render-flow-icons.mjs (\`npm run flow-icons\`); don't edit.
// The Flow Buttons icons as PNG data URLs for the settings' previews. \`d\` is the path each was drawn from, so a
// test notices when the widget's icons change and this wasn't re-rendered.
export const FLOW_ICON_IMAGES: Record<string, { d: string, image: string }> = {
${lines.join('\n')}
};
`);
console.log(`${lines.length} icons → lib/flowIconImages.ts`);
